"""
This not-so-little tool is not used directly in the Brute production pipeline.

It is an academic tool to experiment with what factors correlate with Zwift's
inscrutable zFTP (if any) and by how much (if at all). In each run, this tool
simply displays a pretty matplotlib chart. It is of academic interest only.
Note that the ZwiftRacing app also reports a ZFTP, but they are not one and
the same. For some riders, their Zwift profile has an entry for FTP, which is
not the same as either of these. Perhaps it is a number derived from a formal
FTP test in Zwift.

This tool performs regression modeling on 90-day best power, Zsun curves, and
Zwift zFTP data for Zwift riders using sklearn and scipy. It is our foremost
usage of machine-learning in the Brute project. It is our most sophisticated
example of matplotlib to create pretty charts. Results are not printed or
saved in a file; charts are displayed in a window for visualization. There are
a sequence of many tests here: you can comment out the sections you do not
want to run, or run them all in sequence. The code is commented to explain
what each section does.

The dataset on which this tool operates is generated by brute08.py. Don't run
this tool until you have run brute08.py first_name. Tool08.py inputs the thousands
of files scraped by DaveK from Zwift, ZwiftPower, and ZwiftRacingApp and
generates a single output file of data for subsequent regression modelling
which serves as the input file for this tool12.py. For some takeaways, see the
comments in the model sections below.

The script performs the following steps:
- Configures logging for the application.
- Loads a dataset of rider best power and model training items from a JSON file.
- Filters out incomplete or invalid data entries to create a clean sample for
  analysis.
- Visualizes relationships between various ZwiftPower 90-day best power values
  (at multiple durations) and FTP values from ZwiftProfile and ZwiftRacingApp
  using scatter plots.
- (Commented sections) Provides templates for multiple linear regression
  analyses to predict zFTP from different combinations of best power features,
  including feature selection and model evaluation.
- Compares the predicted 40-minute power from a custom model (zsun TTT model)
  to the actual 40-minute ZwiftPower best value, evaluating the model's
  accuracy and visualizing predicted vs. actual values.

This tool demonstrates data cleaning, feature engineering, regression modeling,
and visualization for cycling performance analytics using Python numpy, sklearn,
scipy, and matplotlib.
"""

