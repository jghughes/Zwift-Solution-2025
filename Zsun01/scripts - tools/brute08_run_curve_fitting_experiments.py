from zwiftpower_flattened_90_day_watts_item import ZwiftPowerFlattened90dayWattsItem

import time
import logging
from jgh_exceptions import AlertMessageError
from jgh_logging import setup_json_logging, log_event
from storage_config import DIRPATH_LOGGING


def run_curve_fitting_experiments():

    try:
        throw_if_any_dirpath_invalid_or_not_exists([Path(DIRPATH_VISUAL_STUDIO_PYTHON_PROJECT), Path(DIRPATH_ZWIFTPOWER_90_DAY_BEST_FILES), Path(DIRPATH_ZWIFT_FILES), Path(DIRPATH_RUBBISH_SCRATCHPAD)])
    except Exception as err:
        print(err)
        return

    try:
        throw_if_any_filename_invalid([FILENAME_RIDER_BRUTE_DTO_JSON_DICT, regression_filename_excel, regression_filename_json_generated_by_tool08, curve_fitting_filename_for_excel])
    except Exception as err:
        print(err)
        return

    dict_of_zwift_profiles_for_everybody = read_zwiftdto_files_to_item_dict_sync(Path(DIRPATH_ZWIFT_FILES), None) 
 
    dict_of_zsun_watts_graphs_for_everybody = read_zwiftpower90daywattsdto_files_to_item_dict_sync(Path(DIRPATH_ZWIFTPOWER_90_DAY_BEST_FILES),None)

    print(f"Successfully read, validated, and loaded {len(dict_of_zsun_watts_graphs_for_everybody)} 90-day best graphs from ZwiftPower files in:- \nDir : {DIRPATH_ZWIFTPOWER_90_DAY_BEST_FILES}\n\n")

    # create a list of zwiftrider objects from the raw data

    total_count = 0
    skipped_modelling_count = 0
    valid_count = 0
    count_of_riders_with_high_fidelity_models = 0
    count_of_riders_with_low_fidelity_models = 0


    zwiftIds_with_high_fidelity : list[str] = []
    zwiftids_with_low_fidelity : list[str] = []

    power_curves_for_everybody : dict[str, CurveFittingResultItem] = {}

    for my_zwiftID, my_zsunwattsgraphitem in dict_of_zsun_watts_graphs_for_everybody.items():

        my_zsunwattsgraphitem.zwift_id = my_zwiftID

        total_count += 1

        # skip riders with no data
        datapoints = my_zsunwattsgraphitem.export_all_x_y_ordinates()

        if not datapoints:
            print(f"ZwiftID {my_zsunwattsgraphitem.zwift_id} has no datapoints")
            skipped_modelling_count += 1
            continue

        #skip riders where all the datapoints are zero
        if all(value == 0 for value in datapoints.values()):
            print(f"ZwiftID {my_zsunwattsgraphitem.zwift_id} has empty data")
            skipped_modelling_count += 1
            continue
        
        # succeess - on we go

        # obtain raw xy data for the various ranges - critical_power, pull, and ftp

        raw_xy_data_cp = my_zsunwattsgraphitem.export_x_y_ordinates_for_cp_w_prime_modelling()
        raw_xy_data_pull = my_zsunwattsgraphitem.export_x_y_ordinates_for_pull_zone_modelling()
        raw_xy_data_one_hour = my_zsunwattsgraphitem.export_x_y_ordinates_for_one_hour_zone_modelling()

        # skip riders where any of the three datasets contain less than 5 points
        if len(raw_xy_data_cp) < 5 or len(raw_xy_data_pull) < 5 or len(raw_xy_data_one_hour) < 5:
            print(f"ZwiftID {my_zsunwattsgraphitem.zwift_id} has insufficient data for curve fitting")
            skipped_modelling_count += 1
            continue

        # do power modelling
    
        critical_power, anaerobic_work_capacity, _, _, _  = do_curve_fit_with_cp_w_prime_model(raw_xy_data_cp)
        coefficient_pull, exponent_pull, r_squared_pull, _, _ = do_curve_fit_with_decay_model(raw_xy_data_pull)
        coefficient_one_hour, exponent_one_hour, r_squared_one_hour, _, _ = do_curve_fit_with_decay_model(raw_xy_data_one_hour)

        pull_short = decay_model_numpy(np.array([300]), coefficient_pull, exponent_pull)
        pull_medium = decay_model_numpy(np.array([600]), coefficient_pull, exponent_pull)
        pull_long = decay_model_numpy(np.array([1800]), coefficient_pull, exponent_pull)
        one_hour = decay_model_numpy(np.array([60*60]), coefficient_one_hour, exponent_one_hour)

        # load results into answer
        
        #load results into a dataclass
        curve = CurveFittingResultItem(
            zwift_id=my_zwiftID,
            sixty_min_curve_coefficient=coefficient_one_hour,
            sixty_min_curve_exponent=exponent_one_hour,
            sixty_min_curve_r_squared=round(r_squared_one_hour, 2),
            TTT_pull_curve_coefficient=coefficient_pull,
            TTT_pull_curve_exponent=exponent_pull,
            TTT_pull_curve_r_squared=round(r_squared_pull, 2),
            CP=round(critical_power),
            AWC=round((anaerobic_work_capacity / 1_000.0), 1),
            when_curves_fitted=get_current_utc_iso8601_timestamp()
        )
        power_curves_for_everybody[str(my_zsunwattsgraphitem.zwift_id)] = curve

        # log results for my_zsunwattsgraphitem

        summary_cp_w_prime  =  f"Zsun CP = {round(critical_power)}W  AWC = {round(anaerobic_work_capacity/1_000)}kJ"
        summary_pull = f"TTT pull power (30 - 60 - 120 seconds) = {round(pull_short[0])} - {round(pull_medium[0])} - {round(pull_long[0])}W"
        summary_one_hour = f"One hour power = {round(one_hour[0])}W"

        print(f"\n{summary_cp_w_prime}")
        print(f"{summary_pull}")
        print(f"{summary_one_hour}")


        if r_squared_one_hour >= _minimum_required_r_squared_fit_for_one_hour_power_curve:
            zwiftIds_with_high_fidelity.append(my_zsunwattsgraphitem.zwift_id)
            count_of_riders_with_high_fidelity_models += 1
        else:
            zwiftids_with_low_fidelity.append(my_zsunwattsgraphitem.zwift_id)
            count_of_riders_with_low_fidelity_models += 1

        valid_count += 1

    modelled_count = total_count - skipped_modelling_count

    print(f"\nTotal riders on ZwiftPower from DaveK: {total_count}  Insufficient data : {skipped_modelling_count}  Modelled count: {modelled_count}\n")

    print(f"Riders with excellent TTT pull curve fits [r_squared > {minimum_required_r_squared_fit_for_one_hour_power_curve}] : {count_of_riders_with_high_fidelity_models} ({round(100.0*count_of_riders_with_high_fidelity_models/modelled_count)}%)")

    # for  zwiftIds_with_high_fidelity, write out the zwift_id, name, critical_power, and r_squared_cp. sorted by name
    zwiftIds_with_high_fidelity.sort(key=lambda x: x)
    for zwift_id in zwiftIds_with_high_fidelity:
        print(f"ZwiftID {zwift_id} {dict_of_zwift_profiles_for_everybody[zwift_id].first_name} {dict_of_zwift_profiles_for_everybody[zwift_id].last_name}")

    print(f"\nRequired r_squared threshold (for this test): {_minimum_required_r_squared_fit_for_one_hour_power_curve}")
    print(f"Total in sample : {total_count}\nTotal valid: {valid_count}\nTotal exceeding r2 threshold (1-hr): {count_of_riders_with_high_fidelity_models}\nTotal exceeding r2 threshold (1-hr)%: {round(count_of_riders_with_high_fidelity_models *100/valid_count)}%\n")

    import pandas as pd
    from dataclasses import asdict

    # Create the first_name DataFrame from dict_of_zwift_profiles_for_everybody
    df1 = pd.DataFrame([asdict(value) for value in dict_of_zwift_profiles_for_everybody.values()])

    # Create the second DataFrame from power_curves_for_everybody
    df2 = pd.DataFrame([asdict(value) for value in power_curves_for_everybody.values()])

    # Merge the two DataFrames on the identifier columns
    merged_df = pd.merge(df1, df2, left_on="zwift_id", right_on="zwift_id", suffixes=('_profile', '_power'))

    # write to excel
    write_excel_file(Path(DIRPATH_RUBBISH_SCRATCHPAD), curve_fitting_filename_for_excel, merged_df)
    print(f"\nSaved {len(merged_df)} power curve fitting results to: {DIRPATH_RUBBISH_SCRATCHPAD + curve_fitting_filename_for_excel}\n")

    # map zwiftIds_with_high_fidelity into a list of custom objects and save to json file for use for sophisicated machine learning to determine zFTP

    repository : RepositoryOfRiders = RepositoryOfRiders()

    # AOK. Restart from the beginning with concise dataload. HEAP POWERFUL
    repository.populate_repository(None, DIRPATH_ZWIFT_FILES, DIRPATH_ZWIFTRACINGAPP_FILES, DIRPATH_ZWIFTPOWER_90_DAY_BEST_FILES)
    
    dict_of_RiderItem : Dict[str, RiderBruteItem] = repository.get_dict_of_RiderBruteItem_by_ids(zwiftIds_with_high_fidelity)
    dict_of_zp_90day_graph_watts : Dict[str,ZwiftPowerFlattened90dayWattsItem] = repository.get_dict_of_ZwiftPower90dayWattsItem_by_ids(zwiftIds_with_high_fidelity)
    
    dict_of_riders_with_high_fidelity : Dict[str, RegressionModellingItem] = defaultdict(RegressionModellingItem)

    for ID in zwiftIds_with_high_fidelity:
        zwiftItem = dict_of_zwift_profiles_for_everybody[ID]
        riderItem = dict_of_RiderItem[ID]
        zp_90day_best = dict_of_zp_90day_graph_watts[ID]
        dict_of_riders_with_high_fidelity[ID] = RegressionModellingItem(
            zwift_id					= ID,
            name						= riderItem.name,
            gender						= riderItem.gender,
            weight_kg					= riderItem.weight_kg,
            height_cm					= riderItem.height_cm,
            age_years					= riderItem.age_years,
            zwift_racing_score				= riderItem.zwift_racing_score,
            zwift_cat_open				= riderItem.zwift_cat_open,
            zwift_ftp_watts				= zwiftItem.ftp_on_zwift,
            jgh_60_min_watts			= round(riderItem.get_1_hour_curvefit_watts()),
            jgh_40_minute_watts			= round(riderItem.get_n_second_curvefit_y_ordinate_watts(2400)),
            velo_zpftp_watts		= riderItem.velo_zwiftpower_zFTP_watts,
            velo_rating_30_days	= riderItem.velo_rating_30_days,
            velo_cat_num_30_days	= riderItem.velo_cat_num_30_days,
            velo_cat_name_30_days	= riderItem.velo_cat_name_30_days,
            bp_5						= zp_90day_best.bp_5,
            bp_15						= zp_90day_best.bp_15,
            bp_30						= zp_90day_best.bp_30,
            bp_60						= zp_90day_best.bp_60,
            bp_180						= zp_90day_best.bp_180,
            bp_300						= zp_90day_best.bp_300,
            bp_600						= zp_90day_best.bp_600,
            bp_720						= zp_90day_best.bp_720,
            bp_900						= zp_90day_best.bp_900,
            bp_1200						= zp_90day_best.bp_1200,
            bp_1800						= zp_90day_best.bp_1800,
            bp_2400						= zp_90day_best.bp_2400,
            jgh_60_min_curve_coefficient	= riderItem.jgh_60_min_curve_coefficient,
            jgh_60_min_curve_exponent		= riderItem.jgh_60_min_curve_exponent
    )

    # Create the third DataFrame from dict_of_riders_with_high_fidelity
    riders = dict_of_riders_with_high_fidelity.values()
    df3 = pd.DataFrame([asdict(modelTrainingItem) for modelTrainingItem in riders])

    write_excel_file(Path(DIRPATH_RUBBISH_SCRATCHPAD), regression_filename_excel, df3)
    print(f"\nSaved {len(df3)} correlation data-set items to: {DIRPATH_RUBBISH_SCRATCHPAD}{regression_filename_excel}\n")

    write_with_json_file_ext_dict_of_RegressionModellingDto(Path(DIRPATH_RUBBISH_SCRATCHPAD),regression_filename_json_generated_by_tool08, dict_of_riders_with_high_fidelity)

    # runner

#test runner
